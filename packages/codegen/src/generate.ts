import {
  buildElementTree,
  type DefinitionSet,
  type ElementDefinitionType,
  type ElementNode,
  type StructureDefinition,
} from '@fhirforge/definitions';
import { TsModule } from './module.js';
import { compileSearchParameters, renderSearchModule } from './search.js';
import {
  capitalize,
  jsDoc,
  nestedTypeName,
  primitiveAlias,
  primitiveJsType,
  propName,
  systemTypeToPrimitive,
} from './naming.js';

export interface GenerateOptions {
  /** Required code bindings with more codes than this stay `string`. Default 100. */
  maxBindingCodes?: number;
}

export interface GeneratedFiles {
  /** Relative path (e.g. `resources/Patient.ts`) → file contents. */
  files: Map<string, string>;
  resourceTypes: string[];
  /** Compiled (resource, search parameter) pairs, and how many could not be compiled. */
  searchParameterCount: number;
  unsupportedSearchParameterCount: number;
  complexTypes: string[];
  primitiveTypes: string[];
}

const FHIR_TYPE_EXT = 'http://hl7.org/fhir/StructureDefinition/structuredefinition-fhir-type';
const ABSTRACT_RESOURCE_CODES = new Set(['Resource', 'DomainResource', 'MetadataResource', 'CanonicalResource']);
const RESERVED_NAMES = new Set(['Resource', 'ResourceType', 'ResourceTypeMap', 'OneOf', 'OptionalOneOf', 'ReferenceString']);

const M = {
  helpers: 'helpers',
  primitives: 'primitives',
  datatypes: 'datatypes',
  resourceMap: 'resource-map',
  resource: (name: string) => `resources/${name}`,
};

/**
 * Generates TypeScript types for one FHIR version.
 *
 * Output layout:
 * - `primitives.ts`  FhirString, FhirDateTime, ... (aliases for JSON value types)
 * - `datatypes.ts`   complex types (HumanName, Quantity, generic Reference<T>, ...)
 * - `resources/*.ts` one module per resource, with its backbone elements
 * - `resource-map.ts` ResourceTypeMap, ResourceType and the Resource union
 * - `helpers.ts`     OneOf / OptionalOneOf (choice types) and ReferenceString<T>
 * - `index.ts`       re-exports everything
 */
export function generateTypes(defs: DefinitionSet, options: GenerateOptions = {}): GeneratedFiles {
  const maxBindingCodes = options.maxBindingCodes ?? 100;
  const primitives = defs.primitiveTypes();
  const complex = defs.complexTypes();
  const resources = defs.resources().filter((sd) => !sd.abstract);

  const primitiveCodes = new Set(primitives.map((sd) => sd.type));
  const resourceNames = new Set(resources.map((sd) => sd.type));
  const topLevelNames = new Set<string>([
    ...RESERVED_NAMES,
    ...resourceNames,
    ...complex.map((sd) => sd.type),
    ...primitives.map((sd) => primitiveAlias(sd.type)),
  ]);

  const header = `// Generated by @fhirforge/codegen for FHIR ${defs.fhirVersion}. Do not edit by hand; run \`pnpm gen:r4\`.`;
  const files = new Map<string, string>();

  // ---- primitives ----
  const prim = new TsModule(M.primitives);
  for (const sd of primitives) {
    prim.push(...jsDoc(`${sd.type}: ${sd.description ?? ''}`), `export type ${primitiveAlias(sd.type)} = ${primitiveJsType(sd.type)};`, '');
  }
  files.set(`${M.primitives}.ts`, prim.render(header));

  // ---- helpers ----
  const helpers = new TsModule(M.helpers);
  helpers.use('Resource', M.resourceMap);
  helpers.push(
    '/** Exactly one property of T is set; the others must be absent. Used for required choice elements (`value[x]`). */',
    'export type OneOf<T> = {',
    '  [K in keyof T]: { [P in K]: T[P] } & { [P in Exclude<keyof T, K>]?: never };',
    '}[keyof T];',
    '',
    '/** At most one property of T is set. Used for optional choice elements (`value[x]`). */',
    'export type OptionalOneOf<T> = OneOf<T> | { [P in keyof T]?: never };',
    '',
    '/**',
    ' * A literal reference to a resource of type T: `Patient/123`, an absolute URL ending in',
    ' * `/Patient/123`, a contained reference (`#id`) or a `urn:uuid:` / `urn:oid:` reference.',
    ' * Plain `string` when T is any resource.',
    ' */',
    'export type ReferenceString<T extends Resource = Resource> = Resource extends T',
    '  ? string',
    "  : `${T['resourceType']}/${string}` | `${string}/${T['resourceType']}/${string}` | `#${string}` | `urn:uuid:${string}` | `urn:oid:${string}`;",
  );
  files.set(`${M.helpers}.ts`, helpers.render(header));

  // ---- datatypes and resources ----
  const ctx: Shared = { defs, primitiveCodes, resourceNames, topLevelNames, maxBindingCodes };
  const datatypes = new TsModule(M.datatypes);
  for (const sd of complex) {
    emitStructure(ctx, datatypes, sd, false);
  }
  files.set(`${M.datatypes}.ts`, datatypes.render(header));

  for (const sd of resources) {
    const mod = new TsModule(M.resource(sd.type));
    emitStructure(ctx, mod, sd, true);
    files.set(`${mod.path}.ts`, mod.render(header));
  }

  // ---- resource map ----
  const map = new TsModule(M.resourceMap);
  map.push('/** Maps each resource type name to its TypeScript type. */', 'export interface ResourceTypeMap {');
  for (const sd of resources) {
    map.push(`  ${sd.type}: ${map.use(sd.type, M.resource(sd.type))};`);
  }
  map.push(
    '}',
    '',
    '/** Every concrete resource type name. */',
    'export type ResourceType = keyof ResourceTypeMap;',
    '',
    '/** Any resource. */',
    'export type Resource = ResourceTypeMap[ResourceType];',
  );
  files.set(`${M.resourceMap}.ts`, map.render(header));

  // ---- search parameters (runtime data, not types) ----
  const search = compileSearchParameters(defs);
  files.set('search-parameters.ts', renderSearchModule(search, header));

  // ---- index ----
  const index = new TsModule('index');
  for (const m of [M.primitives, M.helpers, M.datatypes, M.resourceMap, ...resources.map((sd) => M.resource(sd.type))]) {
    index.push(`export type * from './${m}.js';`);
  }
  files.set('index.ts', index.render(header));

  return {
    files,
    searchParameterCount: Object.values(search.table).reduce((n, params) => n + params.length, 0),
    unsupportedSearchParameterCount: Object.values(search.unsupported).reduce((n, list) => n + list.length, 0),
    resourceTypes: resources.map((sd) => sd.type),
    complexTypes: complex.map((sd) => sd.type),
    primitiveTypes: primitives.map((sd) => sd.type),
  };
}

interface Shared {
  defs: DefinitionSet;
  primitiveCodes: Set<string>;
  resourceNames: Set<string>;
  topLevelNames: Set<string>;
  maxBindingCodes: number;
}

interface StructureCtx extends Shared {
  mod: TsModule;
  sd: StructureDefinition;
  /** Element path → generated name, for nodes that become their own type. */
  nested: Map<string, string>;
}

function emitStructure(shared: Shared, mod: TsModule, sd: StructureDefinition, isResource: boolean): void {
  const tree = buildElementTree(sd);
  const nested = new Map<string, string>();
  const order: ElementNode[] = [];
  const collect = (node: ElementNode) => {
    for (const child of node.children) {
      if (child.children.length > 0) {
        let name = nestedTypeName(child.path);
        if (shared.topLevelNames.has(name)) name += 'Backbone';
        nested.set(child.path, name);
        order.push(child);
      }
      collect(child);
    }
  };
  collect(tree.root);

  const ctx: StructureCtx = { ...shared, mod, sd, nested };
  const isReference = sd.type === 'Reference';
  const name = isReference ? 'Reference<T extends Resource = Resource>' : sd.type;
  if (isReference) mod.use('Resource', M.resourceMap);

  emitNode(ctx, tree.root, name, jsDoc(sd.description ?? sd.type), isResource ? sd.type : undefined);
  for (const node of order) {
    emitNode(ctx, node, nested.get(node.path)!, jsDoc(node.element.short ?? node.path));
  }
}

function emitNode(ctx: StructureCtx, node: ElementNode, name: string, doc: string[], resourceType?: string): void {
  const fields: string[] = [];
  const choices: Array<{ node: ElementNode; required: boolean }> = [];

  if (resourceType) {
    fields.push(`  /** The type of the resource. */`, `  resourceType: '${resourceType}';`);
  }

  for (const child of node.children) {
    const el = child.element;
    if (el.max === '0') continue;
    const required = (el.min ?? 0) >= 1;
    const isArray = el.max !== undefined && el.max !== '1';

    if (child.name.endsWith('[x]')) {
      choices.push({ node: child, required });
      continue;
    }

    const resolved = resolveElementType(ctx, child);
    let ts = resolved.ts;
    // Resource.id is typed as a FHIRPath string in the R4 definitions; it is an `id`.
    if (resourceType && child.name === 'id' && ctx.primitiveCodes.has('id')) ts = ctx.mod.use('FhirId', M.primitives);
    if (ctx.sd.type === 'Reference' && child.path === 'Reference.reference') ts = ctx.mod.use('ReferenceString', M.helpers) + '<T>';
    if (ctx.sd.type === 'Reference' && child.path === 'Reference.type') {
      ts = `Resource extends T ? ${ctx.mod.use('FhirUri', M.primitives)} : T['resourceType']`;
      fields.push(...jsDoc(el.short, '  '), `  ${propName(child.name)}${required ? '' : '?'}: ${ts};`);
      continue;
    }
    fields.push(...jsDoc(el.short, '  '), `  ${propName(child.name)}${required ? '' : '?'}: ${isArray ? arrayOf(ts) : ts};`);
    if (resolved.primitive) {
      const element = ctx.mod.use('Element', M.datatypes);
      fields.push(`  _${child.name}?: ${isArray ? `(${element} | null)[]` : element};`);
    }
  }

  // Exclusive choice types are a union per [x] element; several of them intersect into
  // a cross product. Past MAX_CHOICE_COMBINATIONS (e.g. ElementDefinition's five 50-way
  // choices) TypeScript can't represent it, so those fall back to plain optional fields.
  const combinations = choices.reduce(
    (n, c) => n * ((c.node.element.type?.length ?? 1) + (c.required ? 0 : 1)),
    1,
  );
  const exclusive = combinations <= MAX_CHOICE_COMBINATIONS;
  const unions: string[] = [];
  for (const c of choices) {
    if (exclusive) unions.push(choiceType(ctx, c.node, c.required, fields));
    else choiceFields(ctx, c.node, fields);
  }

  ctx.mod.push(...doc);
  const body = fields.join('\n');
  if (unions.length === 0) {
    ctx.mod.push(`export interface ${name} {`, body, '}', '');
  } else {
    ctx.mod.push(`export type ${name} = {`, body, `} & ${unions.join(' & ')};`, '');
  }
}

const MAX_CHOICE_COMBINATIONS = 2048;

/** Non-exclusive fallback: every variant as an optional field. */
function choiceFields(ctx: StructureCtx, node: ElementNode, fields: string[]): void {
  const base = node.name.slice(0, -3);
  for (const t of node.element.type ?? []) {
    const key = base + capitalize(t.code);
    const resolved = resolveType(ctx, node, t);
    fields.push(`  /** ${escapeDoc(node.element.short ?? base)} (only one ${base}[x] may be set) */`, `  ${key}?: ${resolved.ts};`);
    if (resolved.primitive) fields.push(`  _${key}?: ${ctx.mod.use('Element', M.datatypes)};`);
  }
}

/** `T[]`, parenthesized when T has a top-level union (`('a' | 'b')[]`). */
function arrayOf(ts: string): string {
  let depth = 0;
  for (const ch of ts) {
    if (ch === '<') depth++;
    else if (ch === '>') depth--;
    else if (ch === '|' && depth === 0) return `(${ts})[]`;
  }
  return `${ts}[]`;
}

/** Builds `OneOf<{ valueQuantity: Quantity; valueString: FhirString; ... }>` and adds `_valueString` fields. */
function choiceType(ctx: StructureCtx, node: ElementNode, required: boolean, fields: string[]): string {
  const base = node.name.slice(0, -3);
  const variants: string[] = [];
  for (const t of node.element.type ?? []) {
    const key = base + capitalize(t.code);
    const resolved = resolveType(ctx, node, t);
    variants.push(`  ${key}: ${resolved.ts};`);
    if (resolved.primitive) {
      fields.push(`  _${key}?: ${ctx.mod.use('Element', M.datatypes)};`);
    }
  }
  const helper = ctx.mod.use(required ? 'OneOf' : 'OptionalOneOf', M.helpers);
  return `${helper}<{\n  /** ${escapeDoc(node.element.short ?? base)} */\n${variants.join('\n')}\n}>`;
}

function escapeDoc(s: string): string {
  return s.replace(/\*\//g, '*\\/').replace(/\s+/g, ' ').trim();
}

interface Resolved {
  ts: string;
  /** A FHIR primitive serialized as a JSON value, which may carry a `_name` sibling. */
  primitive: boolean;
}

function resolveElementType(ctx: StructureCtx, node: ElementNode): Resolved {
  const el = node.element;
  if (el.contentReference) {
    const path = el.contentReference.slice(el.contentReference.indexOf('#') + 1);
    const name = ctx.nested.get(path);
    if (!name) throw new Error(`${ctx.sd.type}: contentReference ${el.contentReference} not found`);
    return { ts: name, primitive: false };
  }
  if (node.children.length > 0) {
    return { ts: ctx.nested.get(node.path)!, primitive: false };
  }
  const types = el.type ?? [];
  if (types.length !== 1) {
    throw new Error(`${node.path}: expected one type, got ${types.length}`);
  }
  return resolveType(ctx, node, types[0]!);
}

function resolveType(ctx: StructureCtx, node: ElementNode, t: ElementDefinitionType): Resolved {
  const { mod } = ctx;
  const code = t.code;

  // FHIRPath system types (Element.id, Extension.url): plain values, no `_name` sibling.
  const system = systemTypeToPrimitive(code);
  if (system) {
    const ext = t.extension?.find((e) => e.url === FHIR_TYPE_EXT);
    const fhirType = (ext?.valueUrl ?? ext?.valueUri ?? ext?.valueString ?? system) as string;
    const primitive = ctx.primitiveCodes.has(fhirType) ? fhirType : system;
    return { ts: mod.use(primitiveAlias(primitive), M.primitives), primitive: false };
  }

  if (ctx.primitiveCodes.has(code)) {
    const binding = node.element.binding;
    if (code === 'code' && binding?.strength === 'required' && binding.valueSet) {
      const codes = ctx.defs.expandValueSet(binding.valueSet, { maxCodes: ctx.maxBindingCodes });
      if (codes?.length) {
        return { ts: codes.map((c) => `'${c.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`).join(' | '), primitive: true };
      }
    }
    return { ts: mod.use(primitiveAlias(code), M.primitives), primitive: true };
  }

  if (ABSTRACT_RESOURCE_CODES.has(code)) {
    return { ts: mod.use('Resource', M.resourceMap), primitive: false };
  }

  if (code === 'Reference') {
    const targets = (t.targetProfile ?? []).map((url) => url.slice(url.lastIndexOf('/') + 1));
    const reference = mod.use('Reference', M.datatypes);
    if (targets.length === 0 || targets.some((n) => ABSTRACT_RESOURCE_CODES.has(n) || !ctx.resourceNames.has(n))) {
      return { ts: reference, primitive: false };
    }
    const names = [...new Set(targets)].map((n) => mod.use(n, M.resource(n)));
    return { ts: `${reference}<${names.join(' | ')}>`, primitive: false };
  }

  if (ctx.resourceNames.has(code)) {
    return { ts: mod.use(code, M.resource(code)), primitive: false };
  }

  if (!ctx.defs.getStructureDefinition(code)) {
    throw new Error(`${node.path}: unknown type ${code}`);
  }
  return { ts: mod.use(code, M.datatypes), primitive: false };
}
